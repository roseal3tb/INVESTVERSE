/** عدد الأسئلة اللي تظهر فيها كل شخصية (٧ أو ٦). */
export const appearances = pOrder.reduce(
  (m, k) => ({ ...m, [k]: questions.filter((q) => q.o.some((o) => o.p === k)).length }),
  {} as Record<PKey, number>,
);

export type Ranked = { key: PKey; points: number; pct: number };

/**
 * ترتيب الشخصيات: الأكثر نقاطًا أولًا، وعند التعادل تفوز اللي انختارت في سؤال أحدث (قاعدة الحسم).
 * النسبة = النقاط ÷ عدد الأسئلة اللي ظهرت فيها الشخصية.
 */
export function rank(answers: (PKey | undefined)[]): Ranked[] {
  const pts = {} as Record<PKey, number>;
  const last = {} as Record<PKey, number>;
  answers.forEach((a, i) => {
    if (!a) return;
    pts[a] = (pts[a] ?? 0) + 1;
    last[a] = i;
  });
  return pOrder
    .map((key) => ({
      key,
      points: pts[key] ?? 0,
      pct: Math.round(((pts[key] ?? 0) / appearances[key]) * 100),
    }))
    .sort((x, y) => y.points - x.points || (last[y.key] ?? -1) - (last[x.key] ?? -1));
}

export const scoreResult = (answers: (PKey | undefined)[]): PKey => rank(answers)[0]!.key;

